#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const claudePath = path.join(repoRoot, 'CLAUDE.md');
const checkOnly = process.argv.includes('--check');

const expected = `<!-- Generated by scripts/sync-agent-instructions.mjs. Do not edit directly. -->

# Claude Instructions

@AGENTS.md

Follow the canonical repository contract imported above.
`;

if (checkOnly) {
  let actual = '';
  try {
    actual = await readFile(claudePath, 'utf-8');
  } catch {
    console.error('CLAUDE.md is missing. Run `npm run sync:agents`.');
    process.exit(1);
  }

  if (actual !== expected) {
    console.error('CLAUDE.md is out of sync with AGENTS.md. Run `npm run sync:agents`.');
    process.exit(1);
  }

  console.log('Agent instructions are in sync.');
} else {
  await writeFile(claudePath, expected);
  console.log('Synced CLAUDE.md from AGENTS.md.');
}
