#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const agentsPath = path.join(repoRoot, 'AGENTS.md');
const claudePath = path.join(repoRoot, 'CLAUDE.md');
const checkOnly = process.argv.includes('--check');

const header = `<!-- Generated by scripts/sync-agent-instructions.mjs from AGENTS.md. Do not edit directly. -->

# Claude Instructions

Read and follow the canonical repository instructions below.

---

`;

function withOneTrailingNewline(content) {
  return `${content.replace(/\s+$/u, '')}\n`;
}

const agents = await readFile(agentsPath, 'utf-8');
const expected = withOneTrailingNewline(`${header}${agents}`);

if (checkOnly) {
  let actual = '';
  try {
    actual = await readFile(claudePath, 'utf-8');
  } catch {
    console.error('CLAUDE.md is missing. Run `npm run sync:agents`.');
    process.exit(1);
  }

  if (actual !== expected) {
    console.error('CLAUDE.md is out of sync with AGENTS.md. Run `npm run sync:agents`.');
    process.exit(1);
  }

  console.log('Agent instructions are in sync.');
} else {
  await writeFile(claudePath, expected);
  console.log('Synced CLAUDE.md from AGENTS.md.');
}
